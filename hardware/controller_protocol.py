"""Versioned BLE packets for the ESP32 controller bench firmware.

All packets fit in the default 20-byte BLE ATT payload. Integers are little
endian. A session is generated by the ESP32 on each connection, so packets from
an earlier connection cannot arm or move a new one. Motion leases begin when the
ESP32 receives a valid packet; BLE ordering plus sequence checks reject replay.
"""
from dataclasses import dataclass
from enum import IntEnum
import struct


VERSION = 1
MAX_LINEAR_MMPS = 200
MAX_ANGULAR_MRADPS = 500
MIN_LEASE_MS = 100
MAX_LEASE_MS = 500

SERVICE_UUID = "12345678-1234-1234-1234-1234567890ab"
COMMAND_UUID = "abcdefab-1234-5678-1234-abcdefabcdef"
STATUS_UUID = "fedcbafe-4321-8765-4321-fedcbafedcba"


class PacketType(IntEnum):
    STOP = 0
    ARM = 1
    MOTION = 2
    TONE = 3


class ControllerState(IntEnum):
    DISARMED = 0
    ARMED = 1
    MOVING = 2
    FAULT = 3


class Fault(IntEnum):
    NONE = 0
    DISCONNECTED = 1
    BAD_PACKET = 2
    SESSION_MISMATCH = 3
    NOT_ARMED = 4
    COMMAND_EXPIRED = 5
    REPLAYED_SEQUENCE = 6
    OUTSIDE_LIMITS = 7


_HEADER = struct.Struct("<BB")
_SESSION = struct.Struct("<BBI")
_MOTION = struct.Struct("<BBIIHhh")
_STATUS = struct.Struct("<BBBBIIhh")


@dataclass(frozen=True)
class ControllerStatus:
    state: ControllerState
    fault: Fault
    connected: bool
    armed: bool
    has_sequence: bool
    encoder_feedback: bool
    session: int
    last_sequence: int | None
    left_pwm: int
    right_pwm: int


def _u32(value: int, name: str) -> int:
    if type(value) is not int or not 0 <= value <= 0xFFFFFFFF:
        raise ValueError(f"{name} must be an unsigned 32-bit integer")
    return value


def encode_stop() -> bytes:
    return _HEADER.pack(VERSION, PacketType.STOP)


def encode_arm(session: int) -> bytes:
    return _SESSION.pack(VERSION, PacketType.ARM, _u32(session, "session"))


def encode_tone(session: int) -> bytes:
    return _SESSION.pack(VERSION, PacketType.TONE, _u32(session, "session"))


def encode_motion(session: int, sequence: int, lease_ms: int,
                  linear_mmps: int, angular_mradps: int) -> bytes:
    session = _u32(session, "session")
    sequence = _u32(sequence, "sequence")
    values = (lease_ms, linear_mmps, angular_mradps)
    if any(type(value) is not int for value in values):
        raise ValueError("lease and motion values must be integers")
    if not MIN_LEASE_MS <= lease_ms <= MAX_LEASE_MS:
        raise ValueError(f"lease_ms must be {MIN_LEASE_MS}..{MAX_LEASE_MS}")
    if abs(linear_mmps) > MAX_LINEAR_MMPS:
        raise ValueError(f"linear_mmps must be ±{MAX_LINEAR_MMPS}")
    if abs(angular_mradps) > MAX_ANGULAR_MRADPS:
        raise ValueError(f"angular_mradps must be ±{MAX_ANGULAR_MRADPS}")
    return _MOTION.pack(VERSION, PacketType.MOTION, session, sequence,
                        lease_ms, linear_mmps, angular_mradps)


def decode_status(packet: bytes) -> ControllerStatus:
    if len(packet) != _STATUS.size:
        raise ValueError(f"status must be {_STATUS.size} bytes, got {len(packet)}")
    version, state, fault, flags, session, sequence, left, right = _STATUS.unpack(packet)
    if version != VERSION:
        raise ValueError(f"unsupported controller protocol version {version}")
    if flags & 0xF0:
        raise ValueError("status contains unknown flag bits")
    has_sequence = bool(flags & 0x04)
    return ControllerStatus(
        ControllerState(state), Fault(fault), bool(flags & 0x01),
        bool(flags & 0x02), has_sequence, bool(flags & 0x08), session,
        sequence if has_sequence else None, left, right,
    )
